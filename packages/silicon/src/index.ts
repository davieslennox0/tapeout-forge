// packages/silicon: netlist -> structural Verilog -> Tiny Tapeout ttsky wrapper.
// Combinational-only (see checkExportable). LATCH export is refused - see the
// reason string there for why (a real BUILD.md section-0-rule-9 spec conflict
// found while building this, not a guess).

import { Netlist, NandGate, firstOutputSignal } from "@forgeout/core";

export const REQUIRED_SILICON_WORDING =
  "Tapeout-ready export. We have not ordered fabrication. Ordering is a separate paid step that the circuit owner completes on Tiny Tapeout. We do not claim a physical chip exists.";

const MAX_CELLS = 500;
const MAX_PINS = 8;

export type ExportResult =
  | { ok: true; verilog: string; moduleName: string; cellEstimate: number; pinMap: { ui_in: string[]; uo_out: string[] } }
  | { ok: false; reason: string };

/** Checks BUILD.md 4.1's supported-scope rules. Never throws - always returns a specific reason on refusal. */
export function checkExportable(nl: Netlist): { ok: true } | { ok: false; reason: string } {
  if (nl.gates.some((g) => g.kind === "REF")) {
    return {
      ok: false,
      reason:
        "unflattenable REF: this exporter does not flatten REF sub-circuit references (no REF-flattening is implemented); only flat NAND/LATCH netlists are supported",
    };
  }
  if (nl.gates.some((g) => g.kind === "LATCH")) {
    return {
      ok: false,
      reason:
        "latch without a documented reset convention: TAP-02's VERIFIED LATCH semantics (docs/NEW.md latch-reconcile branch: every latch updates unconditionally every tick, state[t+1]=f(state[t],inputs), no enable signal exists in the wire format, no reset/initial-value guarantee) conflict with BUILD.md 4.2's literal instruction to emit 'always_latch', which models a level-sensitive GATED D-latch with an enable pin this format does not have. This is a real BUILD.md section-0 rule-9 spec conflict discovered while building this exporter, not a guessed workaround - reported rather than silently picking one interpretation. LATCH export stays refused until a reset convention is explicitly decided.",
    };
  }
  if (nl.gates.length > MAX_CELLS) {
    return { ok: false, reason: `too large: ${nl.gates.length} gates exceeds the ${MAX_CELLS}-cell supported limit` };
  }
  if (nl.nIn > MAX_PINS || nl.nOut > MAX_PINS) {
    return {
      ok: false,
      reason: `too many pins for the 8-bit in/out wrapper: nIn=${nl.nIn}, nOut=${nl.nOut}, max is ${MAX_PINS} each`,
    };
  }
  return { ok: true };
}

/** Plain structural Verilog for the combinational core (BUILD.md 4.1). Discrete in0..inN/out0..outM ports - easy to testbench directly. */
export function toStructuralVerilog(nl: Netlist, moduleName: string): ExportResult {
  const check = checkExportable(nl);
  if (!check.ok) return check;

  const lines: string[] = [];
  lines.push(`// Generated by forge export-silicon. DO NOT EDIT.`);
  lines.push(`// ${REQUIRED_SILICON_WORDING}`);
  lines.push(`// Reset convention: n/a - this circuit is purely combinational (no LATCH gates).`);
  lines.push(`module ${moduleName} (`);
  const ports: string[] = [];
  for (let i = 0; i < nl.nIn; i++) ports.push(`  input  wire in${i}`);
  for (let k = 0; k < nl.nOut; k++) ports.push(`  output wire out${k}`);
  lines.push(ports.join(",\n"));
  lines.push(`);`);
  lines.push(`  wire s0 = 1'b0;`);
  lines.push(`  wire s1 = 1'b1;`);
  for (let i = 0; i < nl.nIn; i++) lines.push(`  wire s${2 + i} = in${i};`);
  for (let i = 0; i < nl.gates.length; i++) {
    const g = nl.gates[i] as NandGate;
    const sig = 2 + nl.nIn + i;
    lines.push(`  wire s${sig} = ~(s${g.a} & s${g.b});`);
  }
  const firstOut = firstOutputSignal(nl);
  for (let k = 0; k < nl.nOut; k++) lines.push(`  assign out${k} = s${firstOut + k};`);
  lines.push(`endmodule`);

  return {
    ok: true,
    verilog: lines.join("\n"),
    moduleName,
    cellEstimate: nl.gates.length,
    pinMap: {
      ui_in: Array.from({ length: nl.nIn }, (_, i) => `in${i}`),
      uo_out: Array.from({ length: nl.nOut }, (_, k) => `out${k}`),
    },
  };
}

/** Tiny Tapeout ttsky top-module wrapper (BUILD.md 4.2): 8-bit ui_in/uo_out/uio_*, unused outputs tied low. */
export function toTtskyWrapper(nl: Netlist, projectSlug: string): ExportResult {
  const coreName = `${projectSlug}_core`;
  const core = toStructuralVerilog(nl, coreName);
  if (!core.ok) return core;

  const topName = `tt_um_${projectSlug}`;
  const w: string[] = [];
  w.push(`// ${REQUIRED_SILICON_WORDING}`);
  w.push(`module ${topName} (`);
  w.push(`    input  wire [7:0] ui_in,`);
  w.push(`    output wire [7:0] uo_out,`);
  w.push(`    input  wire [7:0] uio_in,`);
  w.push(`    output wire [7:0] uio_out,`);
  w.push(`    output wire [7:0] uio_oe,`);
  w.push(`    input  wire ena,`);
  w.push(`    input  wire clk,`);
  w.push(`    input  wire rst_n`);
  w.push(`);`);
  for (let k = 0; k < nl.nOut; k++) w.push(`  wire w_out${k};`);
  const conns: string[] = [];
  for (let i = 0; i < nl.nIn; i++) conns.push(`.in${i}(ui_in[${i}])`);
  for (let k = 0; k < nl.nOut; k++) conns.push(`.out${k}(w_out${k})`);
  w.push(`  ${coreName} core_inst (`);
  w.push(`    ${conns.join(",\n    ")}`);
  w.push(`  );`);
  const bits: string[] = [];
  for (let i = 7; i >= 0; i--) bits.push(i < nl.nOut ? `w_out${i}` : `1'b0`);
  w.push(`  assign uo_out = {${bits.join(", ")}};`);
  w.push(`  assign uio_out = 8'b0;`);
  w.push(`  assign uio_oe = 8'b0;`);
  const unusedIn = nl.nIn < 8 ? `ui_in[7:${nl.nIn}], ` : "";
  w.push(`  wire _unused = &{ena, clk, rst_n, uio_in, ${unusedIn}1'b0};`);
  w.push(`endmodule`);

  return {
    ok: true,
    verilog: core.verilog + "\n\n" + w.join("\n"),
    moduleName: topName,
    cellEstimate: core.cellEstimate,
    pinMap: core.pinMap,
  };
}
